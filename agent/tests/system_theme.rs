use serde_json::{Value, json};
use tempfile::TempDir;

/*
 * These tests drive the real mirai-agent binary against a fake HOME, so they
 * pin what the hub sees in /metrics and nothing about how the agent gets there.
 * fc-match is a stub on PATH that logs every call, which is how the tests see
 * whether the font is re-read.
 */

